// ─── توابع کمکی لوکالایز ───
// اگر locale برابر "fa" باشد، فیلدهای ترجمه‌شده جایگزین می‌شوند؛
// در غیر این صورت (یا اگر ترجمه‌ای برای آن id موجود نباشد) دیتای اصلی انگلیسی بدون تغییر برگردانده می‌شود.

export function getLocalizedBrand(brand: Brand, locale: string): Brand {
  if (locale !== "fa") return brand;
  const overrides = brandTranslations[brand.id];
  return overrides ? { ...brand, ...overrides } : brand;
}

export function getLocalizedBrands(locale: string): Brand[] {
  return brandsEn.map((b) => getLocalizedBrand(b, locale));
}

export function getLocalizedProduct(product: Product, locale: string): Product {
  if (locale !== "fa") return product;
  const overrides = productTranslations[product.id];
  return overrides ? { ...product, ...overrides } : product;
}

export function getLocalizedProducts(
  products: Product[],
  locale: string,
): Product[] {
  return products.map((p) => getLocalizedProduct(p, locale));
}

